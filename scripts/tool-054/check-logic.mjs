import assert from 'node:assert/strict';
import {TOOL054_LIMITS,tool054FormatClock,tool054HmsToSeconds,tool054LapDuration,tool054ResolveRepeatElapsed,tool054ValidateRepeat} from '../../lib/tool-054-timer-stopwatch.ts';
assert.equal(tool054HmsToSeconds({hours:0,minutes:1,seconds:0}),60);
assert.equal(tool054HmsToSeconds({hours:24,minutes:59,seconds:59}),TOOL054_LIMITS.maxCountdownSeconds);
assert.throws(()=>tool054HmsToSeconds({hours:25,minutes:0,seconds:0}),/COUNTDOWN_LIMIT/);
assert.throws(()=>tool054HmsToSeconds({hours:0,minutes:60,seconds:0}),/INVALID_TIME/);
assert.equal(tool054FormatClock(0,true),'00:00:00.00');
assert.equal(tool054FormatClock(3_661_239,true),'01:01:01.23');
assert.equal(tool054LapDuration(6000,3000),3000);
const c=tool054ValidateRepeat({workSeconds:5,restSeconds:3,rounds:3});
assert.deepEqual(tool054ResolveRepeatElapsed(c,0),{phase:'work',round:1,phaseRemainingMs:5000,completed:false});
assert.deepEqual(tool054ResolveRepeatElapsed(c,5000),{phase:'rest',round:1,phaseRemainingMs:3000,completed:false});
assert.deepEqual(tool054ResolveRepeatElapsed(c,8000),{phase:'work',round:2,phaseRemainingMs:5000,completed:false});
assert.deepEqual(tool054ResolveRepeatElapsed(c,21000),{phase:'completed',round:3,phaseRemainingMs:0,completed:true});
const zeroRest=tool054ValidateRepeat({workSeconds:1,restSeconds:0,rounds:3});
assert.equal(tool054ResolveRepeatElapsed(zeroRest,1999).round,2);
assert.equal(tool054ResolveRepeatElapsed(zeroRest,3000).completed,true);
assert.throws(()=>tool054ValidateRepeat({workSeconds:0,restSeconds:1,rounds:1}),/WORK_RANGE/);
assert.throws(()=>tool054ValidateRepeat({workSeconds:1,restSeconds:0,rounds:100}),/ROUNDS_RANGE/);
console.log('TOOL054 LOGIC PASS');
